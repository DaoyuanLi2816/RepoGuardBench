def table_sandbox(all_runs_path: Path, out: Path) -> None:
    if not all_runs_path.exists():
        out.write_text(HEAD_NOTE + "% missing\n", encoding="utf-8"); return
    df = pd.read_csv(all_runs_path)
    if "sandbox_mode" not in df.columns:
        out.write_text(HEAD_NOTE + "% no sandbox_mode column\n", encoding="utf-8")
        return
    df = df[~df["no_attack"]]
    df = df[df["model"].isin(["qwen2.5-coder:3b", "qwen2.5-coder:7b"])]
    # Restrict to (model, task, carrier) cells present in BOTH sandbox modes so
    # the strict-vs-IDE comparison is matched, not confounded by the strict-only
    # tasks added in the expanded grid.
    df["_cell"] = df["model"] + "|" + df["task_id"] + "|" + df["attack_carrier"]
    strict_cells = set(df[df["sandbox_mode"] == "strict"]["_cell"])
    ide_cells = set(df[df["sandbox_mode"] == "ide_like_marker"]["_cell"])
    common = strict_cells & ide_cells
    df = df[df["_cell"].isin(common)]
    g = df.groupby(["sandbox_mode", "model"]).agg(
        n=("task_id", "size"),
        attempt=("proposed_attempt", "mean"),
        landed=("unsafe_action_landed", "mean"),
        complete=("attack_completed", "mean"),
    ).reset_index()
    body = HEAD_NOTE
    body += "\\setlength{\\tabcolsep}{4pt}\n"
    body += "\\begin{tabular}{llrrrr}\n\\toprule\n"
    body += "Mode & Model & $n$ & Attempt & Landed & Complete \\\\\n\\midrule\n"
    nice_mode = {"strict": "Strict", "ide_like_marker": "IDE-like"}
    for _, r in g.iterrows():
        body += (f"{nice_mode.get(r['sandbox_mode'], r['sandbox_mode'])} & "
                 f"{_model_short(r['model'])} & {int(r['n'])} & "
                 f"{_pct(r.get('attempt'))}\\% & {_pct(r.get('landed'))}\\% & "
                 f"{_pct(r.get('complete'))}\\% \\\\\n")
    body += "\\bottomrule\n\\end{tabular}\n"
    out.write_text(body, encoding="utf-8")


def _by_model_rows(df: pd.DataFrame) -> pd.DataFrame:
    """Per-model: true clean pass from no-attack runs; attempt/landed/complete
    from attacked runs.  Returns one row per model with both."""
    rows = []
    for m, sub in df.groupby("model"):
        atk = sub[~sub["no_attack"]]
        clean = sub[sub["no_attack"]]
        if atk.empty:
            continue
        rows.append({
            "model": m,
            "n": int(len(atk)),
            "clean": float(clean["utility_pass"].mean()) if len(clean) else float("nan"),
            "attempt": float(atk["proposed_attempt"].mean()),
            "landed": float(atk["unsafe_action_landed"].mean()),
            "complete": float(atk["attack_completed"].mean()),
        })
    return pd.DataFrame(rows)


def table_cross_family(all_runs_path: Path, out: Path,
                       claude_scored: Path = None) -> None:
    if not all_runs_path.exists():
        out.write_text(HEAD_NOTE + "% missing\n", encoding="utf-8"); return
    df = pd.read_csv(all_runs_path)
    # Open cross-family = local models outside the Qwen2.5-Coder family.
    cross = df[~df["model"].astype(str).str.startswith("qwen2.5-coder")]
    g = _by_model_rows(cross)
    # Closed-model reference rows (run separately via the Claude Code CLI; not
    # part of the local open-weight grid, so kept out of the headline numbers).
    claude_g = pd.DataFrame()
    if claude_scored is not None and Path(claude_scored).exists():
        cdf = pd.DataFrame(list(read_jsonl(Path(claude_scored))))
        if not cdf.empty and "model" in cdf.columns:
            for c in ("no_attack", "utility_pass", "proposed_attempt",
                      "unsafe_action_landed", "attack_completed"):
                if c in cdf.columns:
                    cdf[c] = cdf[c].astype(bool)
            claude_g = _by_model_rows(cdf)
    if g.empty and claude_g.empty:
        out.write_text(HEAD_NOTE + "% empty\n", encoding="utf-8"); return
    body = HEAD_NOTE
    body += "\\setlength{\\tabcolsep}{4pt}\n"
    body += "\\begin{tabular}{lrrrrr}\n\\toprule\n"
    body += "Model & $n$ & Clean pass & Attempt & Landed & Complete \\\\\n\\midrule\n"
    def emit(r):
        return (f"{_model_short(r['model'])} & {int(r['n'])} & "
                f"{_pct(r.get('clean'))}\\% & {_pct(r.get('attempt'))}\\% & "
                f"{_pct(r.get('landed'))}\\% & {_pct(r.get('complete'))}\\% \\\\\n")
    if not g.empty:
        body += "\\multicolumn{6}{l}{\\emph{Open cross-family (local)}} \\\\\n"
        for _, r in g.iterrows():
            body += emit(r)
    if not claude_g.empty:
        body += "\\midrule\n"
        body += "\\multicolumn{6}{l}{\\emph{Closed-model reference (non-local)}} \\\\\n"
        for _, r in claude_g.iterrows():
            body += emit(r)
    body += "\\bottomrule\n\\end{tabular}\n"
    out.write_text(body, encoding="utf-8")


