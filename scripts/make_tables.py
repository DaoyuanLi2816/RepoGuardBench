def table_stats(core_path: Path, real_path: Path, exclude_path: Path,
                 out: Path) -> None:
    core = list(read_jsonl(core_path))
    real = list(read_jsonl(real_path))
    # Core templates (10 archetypes, instantiated across many module names)
    core_archetypes = {
        "off-by-one", "string-strip", "int-div", "mutable-default",
        "url-join", "exception-type", "recursion-base",
        "sort-key", "mutable-cache", "iterator-double-use",
    }
    # Applied bug families (one task per family)
    applied_families = {
        "ISO-8601", "json-escape", "pathlib-ext", "csv-quote",
        "b64url", "html-strip", "semver-cmp", "gen-double-use",
        "color-short", "argv-flag", "pluralize", "clamp-bounds",
        "caesar", "log-level-cmp",
    }
    def stats(rows):
        if not rows:
            return 0, 0.0, 0.0, 0
        lines = [sum(len(c.splitlines()) for c in r["files"].values()) for r in rows]
        files = [len(r["files"]) for r in rows]
        return len(rows), int(np.median(files)), int(np.median(lines)), max(lines)
    nc, fc, lc, mc = stats(core)
    nr, fr, lr, mr = stats(real)
    nexcl = 0
    if exclude_path.exists():
        with exclude_path.open(encoding="utf-8") as fh:
            for ln in fh:
                if ln.strip() and not ln.startswith("task_id"):
                    nexcl += 1
    body = HEAD_NOTE
    body += "\\setlength{\\tabcolsep}{3pt}\n"
    body += "\\scriptsize\n"
    body += "\\begin{tabular}{lrrrr}\n\\toprule\n"
    body += "Tier & Tasks & Bugs & Files & LOC \\\\\n\\midrule\n"
    body += f"Core & {nc} & {len(core_archetypes)} & {fc} & {lc} \\\\\n"
    body += f"Applied & {nr} & {len(applied_families)} & {fr} & {lr} \\\\\n"
    body += "\\bottomrule\n\\end{tabular}\n"
    out.write_text(body, encoding="utf-8")


def table_main(matched_md_path: Path, out: Path) -> None:
    if not matched_md_path.exists():
        out.write_text(HEAD_NOTE + "% data not yet available\n", encoding="utf-8")
        return
    df = pd.read_csv(matched_md_path)
    if df.empty:
        out.write_text(HEAD_NOTE + "% empty\n", encoding="utf-8")
        return
    # Primary Qwen2.5-Coder family only; cross-family + closed models live in
    # the cross-family table to avoid duplication.
    df = df[df["model"].astype(str).str.startswith("qwen2.5-coder")]
    # Order by size, not lexically (so 14b follows 7b).
    _order = {"qwen2.5-coder:1.5b": 0, "qwen2.5-coder:3b": 1,
              "qwen2.5-coder:7b": 2, "qwen2.5-coder:14b": 3}
    df = df.assign(_o=df["model"].map(lambda m: _order.get(m, 9)))
    df = df.sort_values(["_o", "model", "defense"]).drop(columns="_o")
    body = HEAD_NOTE
    body += "\\setlength{\\tabcolsep}{4pt}\n"
    body += "\\begin{tabular}{llrrrrrrr}\n\\toprule\n"
    body += ("Model & Defense & $n$ & Pass\\,clean & Pass\\,atk & $\\Delta$ "
             "& Attempt & Landed & Complete \\\\\n")
    body += "\\midrule\n"
    last_model = None
    for _, r in df.iterrows():
        m = str(r["model"]); d = str(r["defense"])
        if m != last_model:
            if last_model is not None:
                body += "\\midrule\n"
            last_model = m
        body += (f"{_model_short(m)} & {_defense_short(d)} & "
                 f"{int(r.get('n_matched', 0))} & "
                 f"{_pct(r.get('util_clean_mean'))}\\% & "
                 f"{_pct(r.get('util_mean'))}\\% & "
                 f"{_pct(r.get('util_delta_mean'))}\\% "
                 f"\\scriptsize{{{_ci(r.get('util_delta_lo'), r.get('util_delta_hi'))}}} & "
                 f"{_pct(r.get('attempt_mean'))}\\% & "
                 f"{_pct(r.get('landed_mean'))}\\% & "
                 f"{_pct(r.get('complete_mean'))}\\% "
                 "\\\\\n")
    body += "\\bottomrule\n\\end{tabular}\n"
    out.write_text(body, encoding="utf-8")


